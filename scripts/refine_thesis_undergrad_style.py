def paragraph_text(paragraph: ET.Element) -> str:
    return "".join(node.text or "" for node in paragraph.findall(".//w:t", NS))


def redistribute_text(paragraph: ET.Element, new_text: str) -> None:
    text_nodes = paragraph.findall(".//w:t", NS)
    if not text_nodes:
        return

    remaining = new_text
    for index, node in enumerate(text_nodes):
        if index == len(text_nodes) - 1:
            node.text = remaining
            remaining = ""
            continue

        current = node.text or ""
        take = min(len(current), len(remaining))
        node.text = remaining[:take]
        remaining = remaining[take:]

    if remaining:
        text_nodes[-1].text = (text_nodes[-1].text or "") + remaining


def replace_in_document_xml(xml_bytes: bytes) -> tuple[bytes, int]:
    root = ET.fromstring(xml_bytes)
    replacements = dict(PARAGRAPH_REPLACEMENTS)
    changed = 0

    for paragraph in root.findall(".//w:p", NS):
        old_text = paragraph_text(paragraph)
        new_text = replacements.get(old_text)
        if new_text and new_text != old_text:
            redistribute_text(paragraph, new_text)
            changed += 1

    return ET.tostring(root, encoding="utf-8", xml_declaration=True), changed


def replace_via_word_com(docx_path: Path) -> int:
    word = None
    doc = None
    created_word = False
    opened_here = False
    changed = 0

    pythoncom.CoInitialize()
    try:
        try:
            word = win32com.client.GetActiveObject("Word.Application")
        except Exception:
            word = win32com.client.DispatchEx("Word.Application")
            word.Visible = False
            created_word = True

        full_path = str(docx_path.resolve()).lower()
        for candidate in word.Documents:
            if str(candidate.FullName).lower() == full_path:
                doc = candidate
                break

        if doc is None:
            doc = word.Documents.Open(str(docx_path.resolve()), ReadOnly=False)
            opened_here = True

        for old_text, new_text in PARAGRAPH_REPLACEMENTS:
            search_range = doc.Content
            find = search_range.Find
            find.ClearFormatting()
            find.Replacement.ClearFormatting()
            found = find.Execute(
                FindText=old_text[:80],
                MatchCase=True,
                MatchWholeWord=False,
                MatchWildcards=False,
                MatchSoundsLike=False,
                MatchAllWordForms=False,
                Forward=True,
                Wrap=1,
                Format=False,
            )
            if found and old_text in search_range.Paragraphs(1).Range.Text:
                paragraph_range = search_range.Paragraphs(1).Range
                paragraph_range.Text = new_text + "\r"
                changed += 1

        doc.Save()
        return changed
    finally:
        if doc is not None and opened_here:
            doc.Close()
        if word is not None and created_word:
            word.Quit()
        pythoncom.CoUninitialize()


def refine_document(docx_path: Path, create_backup: bool) -> None:
    if create_backup:
        backup_path = docx_path.with_suffix(docx_path.suffix + ".bak")
        shutil.copy2(docx_path, backup_path)
        print(f"Backup: {backup_path}")

    with zipfile.ZipFile(docx_path, "r") as src:
        file_map = {name: src.read(name) for name in src.namelist()}

    new_xml, changed = replace_in_document_xml(file_map["word/document.xml"])
    file_map["word/document.xml"] = new_xml

    temp_path = docx_path.with_suffix(docx_path.suffix + ".tmp")
    with zipfile.ZipFile(temp_path, "w", zipfile.ZIP_DEFLATED) as dst:
        for name, data in file_map.items():
            dst.writestr(name, data)

    try:
        temp_path.replace(docx_path)
        print(f"Updated: {docx_path}")
        print(f"Changed paragraphs: {changed}")
    except PermissionError:
        temp_path.unlink(missing_ok=True)
        changed = replace_via_word_com(docx_path)
        print(f"Updated via Word COM: {docx_path}")
        print(f"Changed paragraphs: {changed}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("docx_path", type=Path)
    parser.add_argument("--no-backup", action="store_true")
    args = parser.parse_args()

    refine_document(args.docx_path, create_backup=not args.no_backup)


if __name__ == "__main__":
    main()
