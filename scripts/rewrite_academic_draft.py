def normalize_bold_line(line: str) -> tuple[str, bool]:
    match = re.fullmatch(r"\*\*(.+)\*\*", line)
    if match:
        return match.group(1), True
    return line, False


def find_replacement(text: str) -> str | None:
    for prefix, new_text in REPLACEMENTS:
        if text.startswith(prefix):
            return new_text
    return None


def replace_paragraph_text(paragraph, text: str, bold: bool) -> None:
    for child in list(paragraph._p):
        if child.tag != qn("w:pPr"):
            paragraph._p.remove(child)
    run = paragraph.add_run(text)
    if bold:
        run.bold = True


def rewrite_markdown() -> tuple[dict[str, str], int]:
    lines = SOURCE_MD.read_text(encoding="utf-8").splitlines()
    replacement_map: dict[str, str] = {}
    out_lines: list[str] = []
    count = 0
    for line in lines:
        core, is_bold = normalize_bold_line(line)
        replaced = find_replacement(core)
        if replaced is None:
            out_lines.append(line)
            continue
        replacement_map[core] = replaced
        count += 1
        out_lines.append(f"**{replaced}**" if is_bold else replaced)
    OUTPUT_MD.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    return replacement_map, count


def rewrite_docx(replacement_map: dict[str, str]) -> int:
    doc = Document(SOURCE_DOCX)
    count = 0
    for paragraph in doc.paragraphs:
        text = paragraph.text.strip().replace("\t", " ")
        if not text:
            continue
        new_text = replacement_map.get(text)
        if new_text is None:
            continue
        was_bold = any(bool(run.bold) for run in paragraph.runs if run.text.strip())
        replace_paragraph_text(paragraph, new_text, was_bold)
        count += 1
    doc.save(OUTPUT_DOCX)
    return count


def main() -> None:
    replacement_map, md_count = rewrite_markdown()
    docx_count = rewrite_docx(replacement_map)
    print(f"md_replacements={md_count}")
    print(f"docx_replacements={docx_count}")
    print(f"output_md={OUTPUT_MD}")
    print(f"output_docx={OUTPUT_DOCX}")


if __name__ == "__main__":
    main()
