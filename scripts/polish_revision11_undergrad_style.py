def find_source() -> Path:
    matches = sorted(
        path for path in ROOT.glob(SOURCE_PATTERN) if path.is_file() and not path.name.startswith("~$")
    )
    if not matches:
        raise FileNotFoundError("未找到修订版11文档。")
    return matches[0]


def build_output_path(source: Path) -> Path:
    match = re.match(r"(.+)_修订版(\d+)$", source.stem)
    if match:
        prefix = match.group(1)
        revision = int(match.group(2)) + 1
    else:
        prefix = source.stem
        revision = 12

    candidate = source.with_name(f"{prefix}_修订版{revision}{source.suffix}")
    while candidate.exists():
        revision += 1
        candidate = source.with_name(f"{prefix}_修订版{revision}{source.suffix}")
    return candidate


def copy_run_format(src_run, dst_run) -> None:
    dst_run.bold = src_run.bold
    dst_run.italic = src_run.italic
    dst_run.underline = src_run.underline
    dst_run.font.name = src_run.font.name
    dst_run.font.size = src_run.font.size
    if src_run.font.color is not None and src_run.font.color.rgb is not None:
        dst_run.font.color.rgb = src_run.font.color.rgb

    src_rpr = src_run._element.rPr
    if src_rpr is None:
        return

    src_fonts = src_rpr.find(qn("w:rFonts"))
    if src_fonts is None:
        return

    dst_rpr = dst_run._element.get_or_add_rPr()
    dst_fonts = dst_rpr.find(qn("w:rFonts"))
    if dst_fonts is None:
        dst_fonts = OxmlElement("w:rFonts")
        dst_rpr.append(dst_fonts)

    for key in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        value = src_fonts.get(qn(key))
        if value:
            dst_fonts.set(qn(key), value)


def clear_paragraph(paragraph: Paragraph) -> None:
    for child in list(paragraph._p):
        if child.tag != qn("w:pPr"):
            paragraph._p.remove(child)


def replace_paragraph_text(paragraph: Paragraph, new_text: str) -> None:
    template_run = next((run for run in paragraph.runs if run.text), None)
    clear_paragraph(paragraph)
    new_run = paragraph.add_run(new_text)
    if template_run is not None:
        copy_run_format(template_run, new_run)


def verify(source_doc: Document, output_doc: Document) -> None:
    if len(source_doc.paragraphs) != len(output_doc.paragraphs):
        raise RuntimeError(
            f"段落数量发生变化：source={len(source_doc.paragraphs)}, output={len(output_doc.paragraphs)}"
        )

    for index in (14, 16, 18, 19, 20, 35, 55, 133, 162, 259, 299, 337):
        if source_doc.paragraphs[index].text != output_doc.paragraphs[index].text:
            raise RuntimeError(f"不应变化的关键段落被改动：{index}")

    for index in (15, 36, 67, 105, 220, 282, 338, 339, 340):
        if output_doc.paragraphs[index].text != PARAGRAPH_REWRITES[index]:
            raise RuntimeError(f"目标段落未按预期替换：{index}")

    acknowledgements = "".join(output_doc.paragraphs[index].text for index in (338, 339, 340))
    for token in ("首先", "其次", "最后", "我", "我们"):
        if token in acknowledgements:
            raise RuntimeError(f"致谢中仍包含不应保留的表达：{token}")


def main() -> None:
    source = find_source()
    output = build_output_path(source)
    shutil.copy2(source, output)

    source_doc = Document(str(source))
    output_doc = Document(str(output))

    for index, new_text in PARAGRAPH_REWRITES.items():
        replace_paragraph_text(output_doc.paragraphs[index], new_text)

    output_doc.save(str(output))

    verified_output = Document(str(output))
    verify(source_doc, verified_output)

    print(f"SOURCE={source}")
    print(f"OUTPUT={output}")
    print(f"PARAGRAPH_COUNT={len(verified_output.paragraphs)}")
    print(f"PARAGRAPHS_UPDATED={len(PARAGRAPH_REWRITES)}")


if __name__ == "__main__":
    main()
